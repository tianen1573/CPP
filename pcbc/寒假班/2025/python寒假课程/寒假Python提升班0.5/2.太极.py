import turtle as t
t.penup()
t.goto(0,-200)
t.pendown()
t.begin_fill()
t.circle(200,180)
t.circle(100,180)
t.circle(-100,180)
t.end_fill()
t.circle(-200,180)

t.penup()
t.goto(0,70)
t.pendown()
t.color('white')
t.begin_fill()
t.circle(30)
t.end_fill()

t.penup()
t.goto(0,-130)
t.pendown()
t.color('black')
t.begin_fill()
t.circle(30)
t.end_fill()

t.hideturtle()
